export const SKILL_NARRATION_RULES = '正文保持叙事沉浸感：只通过动作、对白、环境和实际后果自然表现行动成败，不复述或播报技能检定结果。正文及角色对白不得出现骰型、骰点、技能加值、技能值、DC、计算公式，或“检定通过/失败”“采用/延后/忽略该检定”等规则性结论；不要让人物知道自己正在投骰或接受技能检定。不要在正文外另加检定摘要、括号注解、系统播报或作者说明来解释结果。世界内本来存在的技艺名称仍可自然使用。需要回报的检定处理、下一轮选择和数值仅写入角色卡原有的 MVU 更新块，照常更新变量；不要把 MVU 数据转述到正文。';

export function dcSkillPrompt(turn) {
    const request = turn.request;
    const levels = ['极易', '容易', '中等', '困难', '很难', '几乎不可能'];
    const guide = [5, 10, 15, 20, 25, 30].map((dc, i) => `${levels[i]} ${Math.round(dc * request.diceSides / 20)}`).join('；');
    const candidates = turn.results.map(r => ({ 检定ID: r.id, 技能名: r.name, 对应事件: r.action, 判定条件: r.conditions,
        骰型: `d${r.sides}`, 技能加值: r.modifier, 骰点: r.result, 总点数: r.total, DC: r.dc, 候选结果: r.passed ? '通过' : '失败' }));
    return `[随机指令工作台 · 技能检定协议 v2]

本次请求ID：${JSON.stringify(request.id)}
技能骰型：d${request.diceSides}
每轮检定上限：${request.maxChecks} 项
技能表：${JSON.stringify(request.skills.map(s => ({ 技能名: s.name, 技能加值: s.modifier })))}
本轮候选检定：${JSON.stringify(candidates)}
DC 难度参考：${guide}。这是参考，可按剧情和用户要求自由设置数值。
计算规则：骰点＋技能加值 ≥ DC 时通过，相等也通过；自然 1 和最大骰点没有自动成败特例。

这是为对话添加意外性的自由辅助工具，以用户最新要求为准。
默认结合用户实际行动，把本地检定结果融入剧情；用户可以沿用、重复、修改或忽略检定，不因回复编辑、骰型变化、条件变化或请求ID不同就宣布检定无效。
不要强迫用户执行预定行动。用户另有要求时按用户要求处理；需要说明本轮怎样使用检定时，仅写入 MVU 的“本轮处理”。
本轮没有候选检定时正常回应。需要掷骰时由插件在下一次发送时本地完成，不要编造插件骰点。
继续遵守角色卡原有的正文格式、篇幅和人物设定；若要求 content 标签包裹正文，保留完整的成对标签，插件说明不计入正文篇幅。
${SKILL_NARRATION_RULES}

为下一轮准备待判定：
${request.mode === 'every' ? '每轮模式：尽量结合剧情提供至少一项。' : '挑战模式：按需要提供检定，没有需要时可留空。'}
最多 ${request.maxChecks} 项，可以重复使用同一技能。优先使用技能表中的名称和加值；表中没有的技能按 +0 处理。
每项填写“技能名”和数值“DC”；建议补充“对应事件”和“判定条件”，也可以省略。选择与难度按用户要求和剧情决定。

沿用角色卡已有的 MVU 更新格式，将完整 JSON 对象写入“随机指令工作台.技能判定”：
{"规则版本":2,"请求ID":${JSON.stringify(request.id)},"本轮处理":[],"待判定":[{"技能名":"技能名称","对应事件":"具体行动","判定条件":"当前条件","DC":15}]}
“本轮处理”可回报候选检定的使用情况：每项包含“检定ID”、“处理”和可选“说明”。处理可写“采用检定”“延后检定”“叙事结算”或“未执行”；没有候选时写 []。
“待判定”为空数组表示不安排下一轮检定。不需要重新安排时也可保留现有待判定。
使用 _.set 时路径为“随机指令工作台.技能判定”；使用 JSON Patch 时路径为“/随机指令工作台/技能判定”，也支持写入整个“/随机指令工作台”对象。
若角色卡用 XML 包裹 JSON Patch，外层标签名为 UpdateVariable，内层标签名为 JSONPatch，内部填写合法JSON操作数组，使用实际尖括号并完整闭合两层标签。
继续按角色卡原有规则更新其他变量，不得覆盖整个 stat_data 或修改角色卡 schema。`;
}
