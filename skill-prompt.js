export function dcSkillPrompt(turn) {
    const request = turn.request;
    const count = `${request.mode === 'every' ? 1 : 0}～${request.maxChecks}`;
    const levels = ['极易', '容易', '中等', '困难', '很难', '几乎不可能'];
    const guide = [5, 10, 15, 20, 25, 30].map((dc, i) => `${levels[i]} ${Math.round(dc * request.diceSides / 20)}`).join('；');
    const candidates = turn.results.map(r => ({ 检定ID: r.id, 技能名: r.name, 对应事件: r.action, 判定条件: r.conditions,
        骰型: `d${r.sides}`, 技能加值: r.modifier, 骰点: r.result, 总点数: r.total, DC: r.dc, 候选结果: r.passed ? '通过' : '失败' }));
    return `[随机指令工作台 · 技能检定协议 v2]

本次请求ID：${JSON.stringify(request.id)}
技能骰型：d${request.diceSides}
下一轮选择数量：${count} 项不同技能
技能表：${JSON.stringify(request.skills.map(s => ({ 技能名: s.name, 技能加值: s.modifier })))}
本轮候选检定：${JSON.stringify(candidates)}
当前骰型的 DC 难度参考：${guide}。这是参考而非强制档位，可以使用中间值。
计算规则：骰点＋技能加值 ≥ DC 时通过，相等通过。自然 1 和最大骰点不自动决定成败，总点数不截断。DC 是正整数，可以高于骰子面数。

一、先判断适用性，再使用结果

候选检定尚不代表剧情中已经发生了相应行动。
请结合用户最新发言和已经成立的剧情事实，逐项判断：用户是否实际执行了对应行动？目标、方法和影响难度的关键条件是否相符？
仅仅使用同一个技能，不代表可以沿用原 DC。目标、方法、工具、环境或其他关键条件改变，导致难度明显升高或降低时，旧检定均不适用。措辞变化和不影响难度的细节变化不构成失效理由。
不得依据骰点好坏决定是否适用；不得为了回避失败、制造成功或满足篇幅，临时虚构条件变化、更换技能或者宣布检定不适用。

二、每项候选检定必须选择一种处理方式

【采用检定】
用户执行了对应行动，关键条件相符。必须采用插件提供的结果：通过表示达成该事件所定义的目标；失败表示未达成该目标。可以描写代价、后果和新的发展，但不得把失败写成该目标已经完成，也不得任意扩大成功范围。
不得修改骰点、加值、DC、总点数或计算结果，不得自行重掷。同轮各项分别处理，允许成功与失败并存。对应行动的成败以采用的检定为准，其他随机剧情指令不得反转它。
已经适用的检定不能因为写作方便而改成叙事结算。

【延后检定】
用户仍在推进相关行动，但关键条件变化使旧检定失效，而新的成败可以自然留待下一轮。本轮可描写准备、过程、互动和其他剧情，但不要提前确定该行动的成败。
在下一轮待判定中，为该技能填写调整后的具体事件、条件和新 DC。不得将旧骰点套用到新 DC；新检定等待下一次用户发送后由插件投骰。

【叙事结算】
旧检定因实际行动或难度变化而失效，并且继续等待会使剧情不自然停滞。由你依据当前情境自行决定实际行动的成败，正常推进剧情。
不得声称这是旧骰子判定的结果，也不得虚构新的掷骰。已经在本轮结算完成的行动，不得再次放入下一轮待判定。

【未执行】
用户放弃、绕过或没有实际执行对应行动，或前置事件使该行动没有发生。忽略该候选结果，不要强迫用户执行预定行动。

三、保持正常的剧情生成

继续遵守角色卡和用户的正文格式、篇幅、人物设定等要求。需要延后时，由你判断能否把尚未解决的挑战自然安排到本轮末尾；不要为了等待检定让整轮剧情停住，也不要提前替用户选择下一步行动。
若角色卡要求正文放在 <content></content> 或其他成对标签内，必须实际输出这些完整标签；不要因为本插件的检定说明而省略正文包裹格式。篇幅要求作用于剧情正文，不能用 MVU、检定回报或规则说明凑字数。
本轮没有候选检定时，正常回应用户，不得虚构骰点。

四、为下一轮选择尚未结算的挑战

根据本轮结束时的实际剧情，从提供的技能表中选择规定数量的不同技能。技能名称必须完全一致，不得自行增加技能或更改加值。
每项必须包含：技能名；对应事件（具体行动、目标以及要判断是否达成的目标）；判定条件（会影响该事件难度的关键条件）；DC（依据事件和条件确定的正整数）。
不要只写“进行撬锁”“接受挑战”等无法判断适用范围的笼统描述。不要选择本轮已经完成或已经明确结算的行动。
不要根据技能加值高低、旧骰点或者希望剧情成功或失败来倒推 DC。
${request.mode === 'every' ? '本次为每轮判定模式：至少选择一项，待判定列表不能留空。' : '本次为有明确挑战模式：没有需要检定的挑战时，待判定写空数组。'}
下一轮选择只是可能发生的挑战，不代表用户已经承诺执行。

五、在本轮 MVU 更新中回报

沿用角色卡已有的 MVU 更新格式，在正常变量更新中增加插件字段。将完整 JSON 对象写入“随机指令工作台.技能判定”，必须包含以下字段（字段名完全一致）：
“规则版本”：数字 2。
“请求ID”：字符串 ${JSON.stringify(request.id)}。
“本轮处理”：数组，为每个本轮候选检定回报一次；每项包含“检定ID”（与候选完全一致）、“处理”（采用检定/延后检定/叙事结算/未执行之一）、“说明”（简短具体结论）。没有候选时写 []。
“待判定”：数组；每项包含“技能名”、“对应事件”、“判定条件”、“DC”。技能名和条件是字符串，DC 必须是 JSON 数字。不要输出骰点、加值或重算后的成败。
说明只需交代实际处理结论，不需要输出详细分析过程。允许没有下一轮检定时，待判定写 []，但仍必须更新整个对象。
必须输出实际可执行的 MVU 更新，不能只在正文或普通代码块里展示 JSON。使用 _.set 时，路径为“随机指令工作台.技能判定”；使用 JSON Patch 时，路径为“/随机指令工作台/技能判定”，使用 add 或 replace 写入完整对象。
若角色卡使用 XML 包裹 JSON Patch，完整格式必须为 <UpdateVariable><JSONPatch>合法JSON操作数组</JSONPatch></UpdateVariable>。必须同时写出 </JSONPatch> 和 </UpdateVariable>，不能只关闭外层标签；检查 JSON 数组、对象和所有标签均完整闭合后再结束回复。
继续按角色卡原有规则更新其他变量，确保正文与变量结果一致。不得覆盖整个 stat_data，不得修改角色卡 schema，不得输出插件内部的 _source，也不得沿用旧请求ID。`;
}
